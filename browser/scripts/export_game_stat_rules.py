assert 'value + GameStats_GetScoreMod(reason) > 99999999'in text
out=ROOT/'browser/src/source/game-stat-rules.ts'
out.write_text('// Generated by browser/scripts/export_game_stat_rules.py from native source.\nexport const NATIVE_GAME_STAT_RULES = '+json.dumps(data,separators=(',',':'))+' as const;\n')
print(f'Exported {len(scores)} score events and {len(wide)} native stat bounds.')
