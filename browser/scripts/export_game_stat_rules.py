"""Export native score weights/stat bounds without inventing browser values."""
from pathlib import Path
import hashlib,json,re
ROOT=Path(__file__).resolve().parents[2]
source=ROOT/'src/game_stats.c';header=ROOT/'include/constants/game_stats.h'
text=source.read_text();constants={name:int(value)for name,value in re.findall(r'^#define\s+(\w+)\s+(\d+)\b',header.read_text(),re.M)}
def array(name):
 body=re.search(r'\b'+name+r'\[\]\s*=\s*\{(.*?)\};',text,re.S).group(1)
 return [int(value)if value.isdigit()else value=='TRUE'for value in re.findall(r'\b(?:\d+|TRUE|FALSE)\b',body)]
