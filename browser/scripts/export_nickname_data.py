"""Pin the original English species-name bank and unambiguous native glyphs.

No original data is modified. Glyph encoding is not an English naming-keyboard
or UI implementation. Duplicate Unicode aliases are deliberately unsupported.
"""
import hashlib
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[2]
OUTPUT=ROOT/'browser/src/source/nickname-data.ts'
SOURCES=['files/msgdata/msg/msg_0237.gmm','charmap.txt','include/constants/charcode.h','include/constants/global.h',
         'include/constants/pokemon.h','src/msgdata.c','src/pokemon.c',
         'src/string_util.c','src/naming_screen.c','src/launch_application.c',
         'src/scrcmd_c.c','src/hatch_egg_task.c','src/battle/battle_command.c','src/npc_trade.c',
         'src/pm_string.c','include/pm_string.h']


def inputs():
    names={int(row.attrib['index']):row.find("language[@name='English']").text
           for row in ET.parse(ROOT/SOURCES[0]).getroot().findall('row')}
    assert set(names)==set(range(496))
    candidates={}
    for line in (ROOT/'charmap.txt').read_text().splitlines():
        match=re.fullmatch(r'([0-9A-Fa-f]{4})=(.)',line)
        if match:
            code=int(match[1],16)
            if code<0xff00 and not 0xd800<=ord(match[2])<=0xdfff:
                candidates.setdefault(match[2],[]).append(code)
    glyphs={char:codes[0] for char,codes in candidates.items() if len(codes)==1}
    assert len(set(glyphs.values()))==len(glyphs),'Distinct represented characters must encode distinctly'
    aliases={char:codes for char,codes in candidates.items() if len(codes)!=1}
    units=[[glyphs[c] for c in names[i]]+[0xffff] for i in range(496)]
    assert all(len(row)<=11 for row in units)
    exported=json.loads((ROOT/'browser/public/source/names.json').read_text())['species']
    assert all(exported[str(i)]==names[i] for i in range(496))
    header=(ROOT/'include/constants/global.h').read_text()
    char_header=(ROOT/'include/constants/charcode.h').read_text()
    assert re.search(r'#define\s+POKEMON_NAME_LENGTH\s+10\b',header)
    assert re.search(r'#define\s+CHAR_SPACE\s+478\b',char_header)
    return names,units,glyphs,aliases


def render():
    names,units,glyphs,aliases=inputs()
    compact=lambda obj:json.dumps(obj,ensure_ascii=True,separators=(',',':'))
    provenance={'bank':237,'language':'English','languageID':2,'eos':65535,'maxLength':10,
                'space':478,'sources':[{'path':p,'sha256':hashlib.sha256((ROOT/p).read_bytes()).hexdigest()}for p in SOURCES]}
    return ('// Generated by browser/scripts/export_nickname_data.py from ORIGINAL sources.\n'
            '// Native glyph encoding only; not the naming UI or keyboard admission policy.\n'
            + 'export const NATIVE_NICKNAME_PROVENANCE=Object.freeze('+compact(provenance)+');\n'
            + 'export const NATIVE_SPECIES_NICKNAMES=Object.freeze('+compact([names[i] for i in range(496)])+');\n'
            + 'export const NATIVE_SPECIES_NICKNAME_CODES=Object.freeze('+compact(units)+'.map(row=>Object.freeze(row)));\n'
            + 'export const NATIVE_NICKNAME_GLYPHS:Readonly<Record<string,number>>=Object.freeze('+compact(glyphs)+');\n'
            + 'export const NATIVE_NICKNAME_AMBIGUOUS_GLYPHS=Object.freeze('+compact(aliases)+');\n')


if __name__=='__main__':
    text=render()
    if '--check' in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text()!=text:
            raise SystemExit('Pinned nickname data does not match original sources')
    else:
        OUTPUT.parent.mkdir(parents=True,exist_ok=True);OUTPUT.write_text(text)
    print(json.dumps({'file':str(OUTPUT.relative_to(ROOT)),
                      'sha256':hashlib.sha256(text.encode()).hexdigest(),
                      'speciesRows':496,'nativeGlyphs':len(inputs()[2])}))
